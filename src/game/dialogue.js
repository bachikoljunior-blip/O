/**
 * 文脈に合う台詞をひとつ選ぶ。
 * 条件つきが該当すればそちらを優先し、無ければ無条件の中から選ぶ。
 * @param {string} pool  POOLS のキー
 * @param {object} ctx   makeContext の戻り値
 * @param {number} salt  同じ NPC が同じ台詞を繰り返さないための種
 */
export function pickLine(pool, ctx, salt = 0) {
  const all = POOLS[pool];
  if (!all || !all.length) return '';
  const fit = all.filter((l) => l.when && l.when(ctx));
  const base = all.filter((l) => !l.when);
  // 条件つきが該当すれば 70% でそちらを使う（状況に反応している感じを出す）
  const use = fit.length && ((salt * 2654435761) % 100) / 100 < 0.7 ? fit : (base.length ? base : fit);
  if (!use.length) return '';
  return use[Math.abs(salt) % use.length].t;
}

