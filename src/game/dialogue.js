// 会話文の台本集。
//
// 台詞は「役割 × 状況」で選ぶ。状況とは時刻・天候・地方・主線の進行・
// 討伐したボス・プレイヤーの様子（手負い／裕福／死にすぎ）のこと。
// 同じ村人でも、雨の夜と晴れた朝では違うことを言う。

/** 会話に使う文脈をゲーム状態から作る */
export function makeContext(npc, game) {
  const p = game.player;
  const q = game.quests;
  const sky = game.sky;
  const h = sky.hour;
  const phase = h < 5 ? 'night' : h < 9 ? 'morning' : h < 16 ? 'day' : h < 19 ? 'dusk' : 'night';
  const bosses = Object.keys(q.flags).filter((k) => k.startsWith('bossDefeated_')).length;
  return {
    phase,
    night: phase === 'night',
    rain: sky.rainAmount > 0.25,
    snow: sky.snowAmount > 0.2,
    fog: sky.fogDensity > 0.05,
    region: npc.poi?.region || 'downs',
    bosses,
    lateGame: bosses >= 3,
    endGame: !!q.flags.dragonKey,
    hurt: p.hp < p.maxHp * 0.4,
    rich: p.echo > 8000,
    poor: p.echo < 200,
    deaths: p.deaths,
    clumsy: p.deaths >= 8,
    kills: p.kills,
    veteran: p.kills >= 120,
    delved: (q.count.dungeonBosses || 0) > 0,
    dragonSlain: !!q.flags.bossDefeated_dragon,
  };
}

